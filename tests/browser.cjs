const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const directory = path.resolve('.build/test-results'); fs.mkdirSync(directory, { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1060 }, deviceScaleFactor: 1 });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:4173';
  try {
    await page.goto(base); await page.locator('#chew-canvas').waitFor();
    await page.screenshot({ path: path.join(directory, 'desktop-fresh.png'), fullPage: true });
    assert.equal(await page.locator('#wear-value').textContent(), '0');
    await page.locator('#chew-button').click();
    assert.equal(await page.locator('#wear-value').textContent(), '7');
    await page.locator('#spit-fibers').click();
    assert.equal(await page.locator('#total-spits').textContent(), '1');
    assert.equal(await page.locator('#spit-fibers').isDisabled(), true);
    await page.locator('[data-pack="200"]').click();
    assert.equal(await page.locator('#remaining').textContent(), '8');
    assert.equal(await page.locator('#current-pack').textContent(), '50 档包装');
    await page.locator('#light-cigarette').click();
    await page.locator('#inhale').click();
    assert.equal(await page.locator('#inhale').isDisabled(), true);
    assert.equal(await page.locator('#exhale').isEnabled(), true);
    await page.locator('#exhale').click();
    assert.equal(await page.locator('#exhale').isDisabled(), true);
    for (let i = 1; i < 15; i++) await page.locator('#chew-button').click();
    assert.equal(await page.locator('#wear-value').textContent(), '100');
    assert.equal(await page.locator('#chew-button').isDisabled(), true);
    assert.equal(await page.locator('#auto-chew').isDisabled(), true);
    await page.screenshot({ path: path.join(directory, 'desktop-chewed.png'), fullPage: true });
    await page.locator('#spit-nut').click();
    assert.equal(await page.locator('#total-discarded').textContent(), '1');
    await page.locator('#chew-button').click();
    assert.equal(await page.locator('#current-pack').textContent(), '200 档包装');
    assert.equal(await page.locator('#remaining').textContent(), '7');
    await page.locator('#auto-chew').check({ force: true });
    await page.waitForTimeout(900);
    assert.ok(Number(await page.locator('#wear-value').textContent()) >= 14);
    await page.locator('[data-page="guide"]').click();
    assert.equal(await page.locator('#auto-chew').isChecked(), false);
    await page.locator('[data-page="pause"]').click();
    await page.locator('#start-breath').click();
    assert.equal(await page.locator('#breath-instruction').textContent(), '轻轻吸气');
    await page.screenshot({ path: path.join(directory, 'breathing.png'), fullPage: true });
    await page.locator('#stop-breath').click();
    await page.locator('[data-page="experience"]').click();
    assert.equal(await page.locator('#nut-status').textContent(), '已吐出 · 空口状态');
    assert.equal(await page.locator('#extinguish').isDisabled(), true);
    await page.locator('#chew-button').click();
    await page.locator('h1').first().click();
    await page.keyboard.press('Space');
    assert.equal(await page.locator('#wear-value').textContent(), '7');
    await page.locator('#sound-toggle').click();
    assert.equal(await page.locator('#sound-toggle').getAttribute('aria-pressed'), 'true');
    await page.reload();
    assert.equal(await page.locator('#sound-toggle').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#total-bites').textContent(), '0');
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.reload(); await page.context().setOffline(true); await page.reload();
    await page.locator('#chew-button').click();
    assert.equal(await page.locator('#wear-value').textContent(), '7');
    await page.context().setOffline(false);
    await page.goto(pathToFileURL(path.resolve('app/index.html')).href);
    await page.locator('#chew-button').click();
    assert.equal(await page.locator('#wear-value').textContent(), '7');
    console.log('PASS: desktop actions, state boundaries, navigation, keyboard, persistence, offline and file://');

    const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
    phone.on('pageerror', error => errors.push(error.message));
    await phone.goto(base);
    assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.ok((await phone.locator('#chew-button').boundingBox()).y + 43 < 844 - 65, 'primary action is above the mobile navigation');
    await phone.screenshot({ path: path.join(directory, 'phone.png'), fullPage: true });
    await phone.locator('#chew-button').tap();
    assert.equal(await phone.locator('#wear-value').textContent(), '7');
    await phone.locator('[data-pack="100"]').tap();
    await phone.locator('#light-cigarette').tap(); await phone.locator('#inhale').tap(); await phone.locator('#exhale').tap();
    await phone.locator('[data-page="pause"]').tap();
    assert.equal(await phone.locator('#pause').isVisible(), true);
    assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await phone.locator('[data-page="guide"]').tap();
    assert.equal(await phone.locator('#guide').isVisible(), true);
    for (const width of [360, 580, 768, 1024]) {
      await phone.setViewportSize({ width, height: 900 });
      await phone.locator('[data-page="experience"]').click();
      assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${width}`);
    }
    console.log('PASS: touch interactions and responsive layouts at 360/390/580/768/1024px');
    const practice = await browser.newPage();
    await practice.clock.install(); await practice.goto(base);
    await practice.locator('[data-page="pause"]').click(); await practice.locator('#start-breath').click();
    await practice.clock.runFor(4100);
    assert.equal(await practice.locator('#breath-instruction').textContent(), '缓缓呼气');
    await practice.clock.runFor(56000);
    assert.equal(await practice.locator('#breath-instruction').textContent(), '做得很好');
    assert.equal(await practice.locator('#start-breath').isVisible(), true);
    console.log('PASS: full 60-second breathing cycle and completion state');
    assert.deepEqual(errors, []); console.log('PASS: no JavaScript runtime errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
