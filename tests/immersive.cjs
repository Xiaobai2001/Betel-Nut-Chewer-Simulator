const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  fs.mkdirSync('.build/test-results', { recursive: true });
  const errors = [];
  const create = async options => { const page = await browser.newPage(options); page.on('pageerror', e => errors.push(e.message)); return page; };
  try {
    const page = await create({ viewport: { width: 1440, height: 940 } });
    await page.goto('http://127.0.0.1:4173');
    await page.locator('#spit-nut').click();
    assert.equal(await page.locator('#light-cigarette').isEnabled(), true);
    await page.keyboard.press('KeyL');
    for (let i = 0; i < 8; i++) { await page.keyboard.press('KeyI'); if (i < 7) await page.keyboard.press('KeyO'); }
    assert.equal(await page.locator('#light-cigarette').isEnabled(), true);
    await page.keyboard.press('KeyL');
    assert.equal(await page.locator('#inhale').isEnabled(), true);
    assert.equal(await page.locator('#exhale').isDisabled(), true);
    await page.keyboard.press('KeyX'); await page.keyboard.press('Space');
    await page.locator('#open-immersive').click();
    await page.waitForFunction(() => document.querySelector('#immersive-scene').dataset.renderer);
    assert.equal(await page.locator('#immersive').isVisible(), true);
    await page.waitForFunction(() => document.fullscreenElement === document.documentElement);
    assert.equal(await page.evaluate(() => document.querySelector('main').inert), true);
    assert.equal(await page.locator('#immersive-scene').getAttribute('data-renderer'), 'webgl');
    await page.waitForTimeout(500);
    await page.screenshot({ path: '.build/test-results/immersive-fresh.png' });
    const bounds = await page.locator('#immersive-canvas').boundingBox();
    await page.mouse.move(bounds.x + bounds.width * .45, bounds.y + bounds.height * .4);
    await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width * .60, bounds.y + bounds.height * .5, { steps: 8 }); await page.mouse.up();
    const rotation = await page.locator('#immersive-scene').getAttribute('data-rotation');
    assert.ok(rotation && rotation !== '-0.300,0.200');
    await page.mouse.wheel(0, -100);
    await page.waitForFunction(() => Number(document.querySelector('#immersive-zoom').value) > 100);
    await page.locator('#immersive-zoom').focus();
    await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#immersive-zoom').inputValue(), '66');
    const bitesBeforeInput = await page.locator('#bite-count').textContent();
    await page.keyboard.press('Space');
    assert.equal(await page.locator('#bite-count').textContent(), bitesBeforeInput);
    await page.locator('#close-immersive').focus();
    await page.keyboard.press('KeyV');
    assert.equal(await page.locator('#immersive [data-view]').count(), 0);
    assert.equal(await page.locator('#immersive-scene').getAttribute('data-scene-view'), 'first');
    await page.keyboard.press('ArrowLeft'); await page.keyboard.press('KeyR');
    assert.equal(await page.locator('#immersive-scene').getAttribute('data-rotation'), '-0.300,0.200');
    assert.equal(await page.locator('#immersive-zoom').inputValue(), '100');
    await page.keyboard.press('Space'); await page.keyboard.press('KeyQ');
    await page.waitForFunction(() => Number(document.querySelector('#immersive-scene').dataset.landed) > 0);
    await page.keyboard.press('Digit3');
    assert.equal(await page.locator('[data-immersive-pack="200"]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#current-pack').textContent(), '50 档包装');
    for (let i = 1; i < 15; i++) await page.keyboard.press('Space');
    assert.equal(await page.locator('#wear-value').textContent(), '100');
    await page.keyboard.press('KeyL'); await page.keyboard.press('KeyI'); await page.keyboard.press('KeyO');
    await page.waitForTimeout(550);
    await page.screenshot({ path: '.build/test-results/immersive-chewed.png' });
    await page.keyboard.press('KeyG');
    await page.waitForFunction(() => Number(document.querySelector('#immersive-scene').dataset.airborne) === 0);
    await page.screenshot({ path: '.build/test-results/immersive-spit.png' });
    await page.locator('#clear-floor').click();
    await page.waitForFunction(() => document.querySelector('#immersive-scene').dataset.landed === '0');
    await page.keyboard.press('Space'); assert.equal(await page.locator('#current-pack').textContent(), '200 档包装');
    await page.keyboard.press('KeyA'); await page.waitForTimeout(850); await page.keyboard.press('KeyA');
    assert.equal(await page.locator('#auto-chew').isChecked(), false);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#immersive').isHidden(), true);
    assert.equal(await page.evaluate(() => document.querySelector('main').inert), false);
    await page.locator('#open-immersive').click();
    await page.locator('#immersive-rest').click();
    assert.equal(await page.locator('#pause').isVisible(), true);
    assert.equal(await page.locator('#nut-status').textContent(), '已吐出 · 空口状态');
    assert.equal(await page.locator('#extinguish').isDisabled(), true);
    console.log('PASS: relight, full-screen first-person-only scene, drag, keys, floor impact and preserved state');

    await page.goto(pathToFileURL(path.resolve('app/index.html')).href);
    await page.locator('#open-immersive').click();
    await page.waitForFunction(() => document.querySelector('#immersive-scene').dataset.renderer === 'webgl');
    await page.locator('#close-immersive').click();
    console.log('PASS: bundled 3D works directly from file://');

    const phone = await create({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    await phone.addInitScript(() => { Element.prototype.requestFullscreen = () => Promise.reject(new Error('Unavailable')); });
    await phone.goto('http://127.0.0.1:4173'); await phone.locator('#open-immersive').tap();
    await phone.waitForTimeout(600);
    await phone.screenshot({ path: '.build/test-results/immersive-phone.png' });
    for (const size of [{ width: 390, height: 844 }, { width: 360, height: 740 }, { width: 844, height: 390 }]) {
      await phone.setViewportSize(size);
      assert.equal(await phone.evaluate(() => document.querySelector('#immersive').scrollWidth <= innerWidth), true);
      await phone.locator('[data-action="chew-button"]').tap();
      assert.equal(await phone.locator('#immersive [data-view]').count(), 0);
      await phone.locator('[data-action="light-cigarette"]').tap();
      await phone.locator('[data-action="inhale"]').tap(); await phone.locator('[data-action="exhale"]').tap();
      await phone.locator('[data-action="extinguish"]').tap();
    }
    await phone.locator('#close-immersive').tap();
    assert.equal(await phone.locator('#immersive').isHidden(), true);
    console.log('PASS: phone portrait/landscape controls and page-filling fallback when full-screen API unavailable');
    const fallback = await create({ viewport: { width: 1000, height: 700 } });
    await fallback.addInitScript(() => { const original = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(type, ...args) { return type.includes('webgl') ? null : original.call(this, type, ...args); }; });
    await fallback.goto('http://127.0.0.1:4173'); await fallback.locator('#open-immersive').click();
    assert.equal(await fallback.locator('#immersive-scene').getAttribute('data-renderer'), 'canvas');
    await fallback.keyboard.press('Space'); await fallback.keyboard.press('KeyQ');
    await fallback.waitForFunction(() => Number(document.querySelector('#immersive-scene').dataset.landed) > 0);
    await fallback.locator('#close-immersive').click();
    assert.deepEqual(errors, []);
    console.log('PASS: no-WebGL compatibility, no uncaught JavaScript errors');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
