CREATE TABLE IF NOT EXISTS chew_users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(24) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL UNIQUE,
  display_name VARCHAR(24) NOT NULL,
  password_hash VARCHAR(200) CHARACTER SET ascii NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chew_activity_daily (
  user_id BIGINT UNSIGNED NOT NULL,
  day DATE NOT NULL,
  nuts_50 BIGINT UNSIGNED NOT NULL DEFAULT 0,
  nuts_100 BIGINT UNSIGNED NOT NULL DEFAULT 0,
  nuts_200 BIGINT UNSIGNED NOT NULL DEFAULT 0,
  completed_50 BIGINT UNSIGNED NOT NULL DEFAULT 0,
  completed_100 BIGINT UNSIGNED NOT NULL DEFAULT 0,
  completed_200 BIGINT UNSIGNED NOT NULL DEFAULT 0,
  cigarettes_lit BIGINT UNSIGNED NOT NULL DEFAULT 0,
  cigarettes_smoked BIGINT UNSIGNED NOT NULL DEFAULT 0,
  cigarettes_finished BIGINT UNSIGNED NOT NULL DEFAULT 0,
  early_extinguished BIGINT UNSIGNED NOT NULL DEFAULT 0,
  early_discarded BIGINT UNSIGNED NOT NULL DEFAULT 0,
  puffs BIGINT UNSIGNED NOT NULL DEFAULT 0,
  breaths BIGINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, day),
  FOREIGN KEY (user_id) REFERENCES chew_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chew_checkins (
  user_id BIGINT UNSIGNED NOT NULL,
  day DATE NOT NULL,
  nut_free BOOLEAN NOT NULL DEFAULT FALSE,
  smoke_free BOOLEAN NOT NULL DEFAULT FALSE,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (user_id, day),
  FOREIGN KEY (user_id) REFERENCES chew_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chew_sessions (
  token_hash CHAR(64) CHARACTER SET ascii NOT NULL PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  expires_at DATETIME(3) NOT NULL,
  INDEX (expires_at),
  FOREIGN KEY (user_id) REFERENCES chew_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chew_runs (
  id CHAR(36) CHARACTER SET ascii NOT NULL PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  last_seq INT UNSIGNED NOT NULL DEFAULT 0,
  state_json JSON NOT NULL,
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX (user_id),
  FOREIGN KEY (user_id) REFERENCES chew_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chew_daily (
  user_id BIGINT UNSIGNED NOT NULL,
  day DATE NOT NULL,
  bites BIGINT UNSIGNED NOT NULL DEFAULT 0,
  nuts_started BIGINT UNSIGNED NOT NULL DEFAULT 0,
  nuts_completed BIGINT UNSIGNED NOT NULL DEFAULT 0,
  spits BIGINT UNSIGNED NOT NULL DEFAULT 0,
  discarded BIGINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, day),
  FOREIGN KEY (user_id) REFERENCES chew_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
